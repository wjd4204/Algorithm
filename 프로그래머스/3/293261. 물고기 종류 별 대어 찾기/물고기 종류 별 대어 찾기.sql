SELECT FI.ID, FO.FISH_NAME, FO.LENGTH
FROM FISH_INFO FI
JOIN (SELECT FI.FISH_TYPE, FNI.FISH_NAME, MAX(FI.LENGTH) AS LENGTH
FROM FISH_INFO FI
INNER JOIN FISH_NAME_INFO FNI ON FI.FISH_TYPE = FNI.FISH_TYPE
GROUP BY FI.FISH_TYPE) FO ON FI.FISH_TYPE = FO.FISH_TYPE
WHERE FI.FISH_TYPE = FO.FISH_TYPE AND FI.LENGTH = FO.LENGTH
ORDER BY FI.ID;