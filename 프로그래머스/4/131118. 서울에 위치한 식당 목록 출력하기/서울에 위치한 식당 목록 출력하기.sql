SELECT RI.REST_ID, RI.REST_NAME, RI.FOOD_TYPE, RI.FAVORITES, RI.ADDRESS, ROUND(RR.SC, 2) AS SCORE
FROM REST_INFO RI
INNER JOIN 
    (SELECT REST_ID, AVG(REVIEW_SCORE) AS SC
    FROM REST_REVIEW
    GROUP BY REST_ID) RR ON RI.REST_ID = RR.REST_ID
WHERE RI.ADDRESS LIKE '서울%'
ORDER BY SCORE DESC, RI.FAVORITES DESC;